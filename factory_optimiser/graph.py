"""Interactive production-flow graph (standalone HTML) for the build plan.

Turns the MILP solution into a directed flow graph of the whole factory:

* **recipe nodes** — machine, recipe, clock (the ``N@% + 1@%`` breakdown from the
  report) and the entry's power draw (plus generation for generators);
* **edges** — every item flow connects the *producing* recipe straight to the
  *consuming* recipe (no intermediate item nodes), annotated with the item name
  and rate (``Iron Ingot 12.4k``). Surplus that is sunk flows into a single
  amber ``Awesome Sink`` node; power is a per-recipe attribute, not an edge.

Because the MILP is a flow balance (not a matching), a producer's output that
several consumers share is decomposed *proportionally*: for item ``i`` with
producers ``p`` (output ``v_p``), consumers ``q`` (demand ``d_q``), flows, and
sink share, the designated edge flow is ``v_p * d_q / C`` for each consumer,
and ``v_p * (1 - C/P)`` to the sink. Edge rates then sum exactly to each
consumer's demand and each producer's output.

The output is a single self-contained ``.html`` file (vis-network from cdnjs,
CSP-friendly), laid out left-to-right by a Python-side layered layout (longest
path, barycenter ordering, per-column non-overlap). Regenerated by the ``graph``
CLI command.
"""

