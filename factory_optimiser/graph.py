EPS = 1e-9


def _machine_palette(machine_ids: list[str]) -> dict[str, dict[str, str]]:
    """Stable, distinct colour per machine type (golden-angle hue walk)."""
    palette: dict[str, dict[str, str]] = {}
    for i, mid in enumerate(machine_ids):
        hue = (i * 137.508) % 360.0
        bg = colorsys.hls_to_rgb(hue / 360.0, 0.70, 0.55)
        border = colorsys.hls_to_rgb(hue / 360.0, 0.42, 0.62)
        palette[mid] = {
            "bg": "#%02x%02x%02x" % tuple(round(c * 255) for c in bg),
            "border": "#%02x%02x%02x" % tuple(round(c * 255) for c in border),
        }
    return palette


def _md(text: str) -> str:
    """Escape vis-network markdown-mode label text (bold/italic triggers)."""
    return text.replace("*", "\\*").replace("_", "\\_")


def build_graph(config: Config, best: AugResult) -> dict:
    """Build the graph data (recipe nodes + item-flow edges) from best."""
    plan = downconvert(config, best.solution)
    recipes_by_id = {r.id: r for r in config.recipes}
    sol = best.solution

    def item(n):
        return config.item_name(n, n)

    # -- recipe rows ----------------------------------------------------------
    rows: list[dict] = []
    for i, m in enumerate(plan):
        recipe = recipes_by_id[m.recipe_id]
        draw, gen = _entry_power(recipe, config, m)
        rows.append(
            {
                "id": f"r{i}",
                "machine": m.machine,
                "machine_title": _machine_title(m.machine),
                "recipe": recipe.name or recipe.id,
                "sloops": m.sloops_per_machine,
                "clock": _clock_breakdown(m),
                "mw": draw,
                "gen_mw": gen,
                "outputs": dict(m.outputs),
                "inputs": dict(m.inputs),
            }
        )

    # -- flow bookkeeping ------------------------------------------------------
    produced_by: dict[str, list[tuple[str, float]]] = {}
    consumed_by: dict[str, list[tuple[str, float]]] = {}
    for r in rows:
        for o, v in r["outputs"].items():
            if v > EPS:
                produced_by.setdefault(o, []).append((r["id"], v))
        for i, v in r["inputs"].items():
            if v > EPS:
                consumed_by.setdefault(i, []).append((r["id"], v))
    total_produced = {it: sum(v for _, v in lst) for it, lst in produced_by.items()}
    total_consumed = {it: sum(v for _, v in lst) for it, lst in consumed_by.items()}

    # -- edges: producer -> consumer (proportional decomposition) --------------
    recipe_flows: dict[tuple[str, str], list[tuple[str, float]]] = {}
    sink_items: dict[str, list[tuple[str, float]]] = {}  # producer id -> sank items

    for it, prod_rows in produced_by.items():
        con_rows = consumed_by.get(it, [])
        total_p = total_produced[it]
        total_c = sum(v for _, v in con_rows)
        for pid, v_p in prod_rows:
            if total_c > 0 and total_p > 0:
                consumed_p = v_p * min(1.0, total_c / total_p)
                for cid, d_q in con_rows:
                    f = consumed_p * d_q / total_c
                    if f > EPS:
                        recipe_flows.setdefault((pid, cid), []).append((it, f))
            else:
                consumed_p = 0.0
            sunk = v_p - consumed_p
            if sunk > EPS:
                sink_items.setdefault(pid, []).append((it, sunk))

    # -- nodes ----------------------------------------------------------------
    machine_ids = sorted({r["machine"] for r in rows})
    palette = _machine_palette(machine_ids)
    legend = sorted(
        (mid, _machine_title(mid), palette[mid]["bg"]) for mid in machine_ids
    )

    nodes: list[dict] = []
    for r in rows:
        label_lines = [
            f"**{_md(r['machine_title'])}**",
            _md(r["recipe"]) + (f"  ({r['sloops']} slp)" if r["sloops"] else ""),
            _md(r["clock"]),
        ]
        pwr = f"{r['mw']:,.0f} MW"
        if r["gen_mw"] > EPS:
            pwr += f" · gen +{r['gen_mw']:,.0f} MW"
        label_lines.append(_md(pwr))
        tips = [f"{r['machine_title']} · {r['recipe']}"]
        if r["sloops"]:
            tips.append(f"{r['sloops']} Somersloop(s)")
        tips.append(r["clock"])
        tips.append(pwr)
        if r["inputs"]:
            tips.append(
                "in: "
                + ", ".join(
                    f"{item(i)} {v:,.1f}" for i, v in sorted(r["inputs"].items())
                )
            )
        if r["outputs"]:
            tips.append(
                "out: "
                + ", ".join(
                    f"{item(o)} {v:,.1f}" for o, v in sorted(r["outputs"].items())
                )
            )
        nodes.append(
            {
                "id": r["id"],
                "kind": "recipe",
                "machine": r["machine"],
                "label": "\n".join(label_lines),
                "title": "\n".join(tips),
            }
        )
    sink_total = sum(v for lst in sink_items.values() for _, v in lst)
    nodes.append(
        {
            "id": "sink",
            "kind": "sink",
            "label": f"**Awesome Sink**\n{sink_total:,.1f} items/min",
            "title": f"Awesome Sink — sinks {sink_total:,.1f} items/min total",
        }
    )

    edges: list[dict] = []
    for (a, b), flows in recipe_flows.items():
        edges.append({"from": a, "to": b, "flows": flows})
    for pid, flows in sink_items.items():
        edges.append({"from": pid, "to": "sink", "flows": flows})
    edges.sort(key=lambda e: e["from"], reverse=True)

    # Layered layout: clean left->right ranks with per-column non-overlap.
    _layered_layout(nodes, edges)

    n_machines = sum(m.machines for m in plan)
    params = config.parameters
    cap_label = (
        f"machine cap {params.machine_cap:,.0f}"
        if params.machine_cap is not None
        else "no machine cap"
    )
    meta = {
        "cap_label": cap_label,
        "points": best.points_per_min,
        "machines": n_machines,
        "power": sol.power_consumed,
        "sloops": f"{sol.sloops_used:g}/{best.sloop_budget:g}",
        "augmenters": best.n_augmenters,
        "n_recipes": len(rows),
        "n_nodes": len(nodes),
        "n_edges": len(edges),
    }

    return {
        "nodes": nodes,
        "edges": edges,
        "machineColors": palette,
        "legend": legend,
        "meta": meta,
    }


# ---------------------------------------------------------------------------
# Layered layout (no-overlap ranks; cycle-safe via SCC condensation)
# ---------------------------------------------------------------------------


def _layered_layout(nodes: list[dict], edges: list[dict]) -> None:
    """Assign (x, y) to each node: a clean layered left->right flow layout.

    1. level = longest path from the sources, via SCC condensation (cycles like
       water/fuel loops collapse to one rank instead of inflating the path);
    2. ordering within each column by barycenter sweeps (fewer crossings);
    3. x = column * XGAP, y = stacked with per-node heights so nodes in a
       column never overlap; columns are vertically centred on the tallest.

    Mutates ``nodes`` in place (adds x / y keys).
    """
    ids = [n["id"] for n in nodes]
    idset = set(ids)
    succ: dict[str, list[str]] = {i: [] for i in ids}
    pred: dict[str, list[str]] = {i: [] for i in ids}
    for e in edges:
        if e["from"] in idset and e["to"] in idset:
            succ[e["from"]].append(e["to"])
            pred[e["to"]].append(e["from"])

    heights = {n["id"]: _est_height(n) for n in nodes}

    # 1) longest-path ranks via SCC condensation.
    comps = _scc_components(ids, succ)
    cid: dict[str, int] = {}
    for ci, comp in enumerate(comps):
        for i in comp:
            cid[i] = ci
    cl = {c: 0 for c in range(len(comps))}
    for _ in range(len(comps) + 1):
        changed = False
        for e in edges:
            cu, cv = cid[e["from"]], cid[e["to"]]
            if cu != cv and cl[cv] < cl[cu] + 1:
                cl[cv] = cl[cu] + 1
                changed = True
        if not changed:
            break
    level = {i: cl[cid[i]] for i in ids}

    # 2) per-column ordering, barycenter sweeps (resources above recipes reads
    #    as "inputs on top, outputs below" for a recipe row). Columns can be
    #    sparse (gaps where no node ranks at a level), so iterate present ones.
    columns: dict[int, list[str]] = {}
    for i in ids:
        columns.setdefault(level[i], []).append(i)
    col_idx = sorted(columns)

    def rank_key(i):
        return (0 if i.startswith("res:") else 1, i)

    for col in columns:
        columns[col].sort(key=rank_key)
    for _ in range(5):
        for col in col_idx:  # downstream sweep
            if col == col_idx[0]:
                continue
            above = {j: k for k, j in enumerate(columns[col - 1])} if col - 1 in columns else {}
            columns[col].sort(
                key=lambda i: (
                    sum(above.get(p, 0) for p in pred[i]) / max(1, len(pred[i])),
                    rank_key(i),
                )
            )
        for col in reversed(col_idx):  # upstream sweep
            if col == col_idx[-1]:
                continue
            below = {j: k for k, j in enumerate(columns[col + 1])} if col + 1 in columns else {}
            columns[col].sort(
                key=lambda i: (
                    sum(below.get(s, 0) for s in succ[i]) / max(1, len(succ[i])),
                    rank_key(i),
                )
            )

    # 3) coordinates: x by column, y stacked by height; centre columns.
    XGAP, YGAP = 270.0, 46.0
    col_totals = {
        col: sum(heights[i] for i in lst) + YGAP * (len(lst) - 1)
        for col, lst in columns.items()
    }
    tallest = max(col_totals.values())
    for col, lst in columns.items():
        yy = (tallest - col_totals[col]) / 2.0
        for i in lst:
            h = heights[i]
            for n in nodes:
                if n["id"] == i:
                    n["x"] = col * XGAP
                    n["y"] = yy + h / 2.0
                    break
            yy += h + YGAP


def _est_height(n: dict) -> float:
    """Approximate rendered vertical extent of a node (label lines * line height)."""
    if n["kind"] == "recipe":
        lines = 4 + (1 if n.get("gen_mw", 0.0) > EPS else 0)
        return lines * 15.0 + 26.0
    return 2 * 15.0 + 22.0


def _scc_components(ids: list[str], succ: dict[str, list[str]]) -> list[list[str]]:
    """Tarjan strongly-connected components (gives a DAG of components)."""
    index: dict[str, int] = {}
    low: dict[str, int] = {}
    onstack: dict[str, bool] = {}
    stack: list[str] = []
    comps: list[list[str]] = []
    counter = 0

    def strongconnect(v: str) -> None:
        nonlocal counter
        index[v] = low[v] = counter
        counter += 1
        stack.append(v)
        onstack[v] = True
        for w in succ[v]:
            if w not in index:
                strongconnect(w)
                low[v] = min(low[v], low[w])
            elif onstack[w]:
                low[v] = min(low[v], index[w])
        if low[v] == index[v]:
            comp: list[str] = []
            while True:
                w = stack.pop()
                onstack[w] = False
                comp.append(w)
                if w == v:
                    break
            comps.append(comp)

    for v in ids:
        if v not in index:
            strongconnect(v)
    return comps


