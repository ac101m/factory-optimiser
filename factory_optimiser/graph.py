def render_html(data: dict) -> str:
    """Render the graph page (self-contained HTML) from build_graph() output."""
    page = _PAGE.replace("__VIS_CDN__", VIS_CDN)
    return page.replace("__DATA__", json.dumps(data))


def optimize_graph(config: Config, best: AugResult) -> str:
    """Convenience: solve data + HTML from a best AugResult (like optimize_markdown)."""
    return render_html(build_graph(config, best))
